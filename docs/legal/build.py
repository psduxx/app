def render(md: str) -> str:
    md = re.sub(r"^\*Draft prepared with AI assistance.*?\*\n+", "", md)
    md = md.replace("(privacy-policy.md)", "(privacy.html)")
    md = re.sub(r"(?<![\w/<])(info@dumc\.com\.au|account@dumc\.com\.au)", r"<\1>", md)
    md = md.replace("www.oaic.gov.au", "[www.oaic.gov.au](https://www.oaic.gov.au)")
    return markdown.markdown(md, extensions=["extra"])


def main() -> None:
    for src, out, title in PAGES:
        body = render((LEGAL / src).read_text(encoding="utf-8"))
        page = TPL.format(
            title=title,
            title_esc=html.escape(title),
            src=src,
            out=out,
            body=body,
            privacy_on=' class="on" aria-current="page"' if out == "privacy.html" else "",
            terms_on=' class="on" aria-current="page"' if out == "terms.html" else "",
        )
        (ROOT / out).write_text(page, encoding="utf-8")
        print(f"{out}: {len(page):,} bytes")


if __name__ == "__main__":
    main()
